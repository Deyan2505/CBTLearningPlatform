namespace CbtLearningPlatform.Client.Curriculum;

/// <summary>Cognitive level of one final-exam item. Fundamental tests a load-bearing concept a learner
/// completing the whole course should retain; Applied requires transferring a course distinction onto a
/// fresh, safe fictional scenario; Integrative requires genuinely combining knowledge from two or more
/// weeks. Level is a deliberate authoring classification, not something derivable from
/// <see cref="FinalExamItem.SourceWeeks"/>.Count — a Fundamental item may still span two weeks (e.g. the
/// schema/core-belief distinction draws on both Week 12 and Week 3).</summary>
public enum ExamQuestionLevel { Fundamental, Applied, Integrative }

/// <summary>One scored item of the course-level final exam, together with the weeks it draws on.
/// <paramref name="SourceWeeks"/> is the coverage claim (which routed week's already-implemented,
/// source-grounded content the item assesses), not new curriculum data — it drives both the coverage
/// tests and the post-submit review links.</summary>
public sealed record FinalExamItem(AssessmentQuestion Question, IReadOnlyList<int> SourceWeeks, ExamQuestionLevel Level);

