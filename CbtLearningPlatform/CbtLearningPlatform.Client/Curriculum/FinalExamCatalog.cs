namespace CbtLearningPlatform.Client.Curriculum;

/// <summary>One scored item of the course-level final exam, together with the weeks it draws on.
/// <paramref name="SourceWeeks"/> is the coverage claim (which routed week's already-implemented,
/// source-grounded content the item assesses), not new curriculum data — it drives both the coverage
/// tests and the post-submit review links. An anchor item names exactly one week; an integrative item
/// names two or more and tests a relationship or distinction that spans them.</summary>
public sealed record FinalExamItem(AssessmentQuestion Question, IReadOnlyList<int> SourceWeeks)
{
    public bool IsIntegrative => SourceWeeks.Count > 1;
    public bool IsAnchor => SourceWeeks.Count == 1;
}

