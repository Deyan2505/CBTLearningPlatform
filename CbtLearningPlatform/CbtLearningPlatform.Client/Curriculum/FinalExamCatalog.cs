    /// <summary>The exam as the shared component consumes it — same FinalAssessmentModel shape every
    /// week uses, so FinalAssessment.razor/FinalAssessmentState need no exam-specific branch. Only
    /// LowScoreInterpretation is set (course-wide wording instead of the per-week default) — every
    /// other scoring rule, band, and threshold is exactly the shared engine's own.</summary>
    public static FinalAssessmentModel Model { get; } = new(
        [.. Items.Select(item => item.Question)],
        LowScoreInterpretation: "Препоръчителен повторен преглед на материала от курса");

    private static FinalExamItem Fundamental(string id, IReadOnlyList<int> weeks, string text, IReadOnlyList<string> options, int correctOptionIndex, string explanation) =>
        Build(id, weeks, ExamQuestionLevel.Fundamental, text, options, correctOptionIndex, explanation);

    private static FinalExamItem Applied(string id, IReadOnlyList<int> weeks, string text, IReadOnlyList<string> options, int correctOptionIndex, string explanation) =>
        Build(id, weeks, ExamQuestionLevel.Applied, text, options, correctOptionIndex, explanation);

    private static FinalExamItem Integrative(string id, IReadOnlyList<int> weeks, string text, IReadOnlyList<string> options, int correctOptionIndex, string explanation) =>
        Build(id, weeks, ExamQuestionLevel.Integrative, text, options, correctOptionIndex, explanation);

    /// <summary>Appends the source week(s) to the explanation as review links. The shared component
    /// already renders Explanation as trusted author markup (weekly assessments use the same pattern
    /// for their Source citations), so the review links need no change to the assessment engine — and
    /// like every explanation, they appear only after submit.</summary>
    private static FinalExamItem Build(string id, IReadOnlyList<int> weeks, ExamQuestionLevel level, string text, IReadOnlyList<string> options, int correctOptionIndex, string explanation)
    {
        string links = string.Join(" · ", weeks.Select(w => $"<a href=\"/kurs/sedmica-{w}\">Седмица {w}</a>"));
        return new(AssessmentQuestion.Choice(id, text, options, correctOptionIndex, $"{explanation} <em>Преговор:</em> {links}"), weeks, level);
    }
